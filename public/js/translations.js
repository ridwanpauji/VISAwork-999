window.applyLanguage = function(lang) {
    if (!lang || !window.visaworkTranslations[lang]) {
        lang = 'id';
    }
    localStorage.setItem('visawork_lang', lang);

    const dict = window.visaworkTranslations[lang];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict && dict[key] !== undefined) {
            if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                el.placeholder = dict[key];
            } else if (el.tagName === 'TITLE') {
                document.title = dict[key];
            } else {
                el.innerHTML = dict[key];
            }
        }
    });

    // Update semua indikator teks bahasa
    document.querySelectorAll('#current-lang, .lang-display-indicator').forEach(el => {
        el.innerText = lang.toUpperCase();
    });

    document.documentElement.lang = lang;
};

window.changeLanguage = function(lang) {
    window.applyLanguage(lang);
};

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('visawork_lang') || 'id';
    window.applyLanguage(savedLang);
});
